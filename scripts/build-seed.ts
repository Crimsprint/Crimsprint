// Builds data/items/math.json (generated, answers verified) and supabase/seed.sql (skills + all items).
// Run: node scripts/build-seed.ts
import assert from 'node:assert/strict'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { templates, generate, type Item } from './math-templates.ts'
import { templates2 } from './math-templates-2.ts'

const root = new URL('..', import.meta.url)
const read = (p: string) => JSON.parse(readFileSync(new URL(p, root), 'utf8'))

// Per template: 20 per skill as 7 easy / 7 medium / 6 hard. The first three non-Algebra skills keep 8 per tier (24).
const perTemplate = (skill: string, tier: string) =>
  ['math.adv.nonlin_eq', 'math.psda.percent', 'math.geo.trig'].includes(skill) ? 8 : tier === 'hard' ? 6 : 7
const math: Item[] = [...templates, ...templates2].flatMap((t, i) => generate(t, perTemplate(t.skill, t.tier), 1000 + i))
writeFileSync(new URL('data/items/math.json', root), JSON.stringify(math, null, 2) + '\n')

// Compact R&W authoring format (data/items/rw/*.json): the key is written first in `c`, with `w` explaining
// each wrong choice in order. The key's letter is derived from the passage so it is stable and spread across A–D.
type Compact = { t: Item['tier']; s: string; p: string; q?: string; c: [string, string, string, string]; w: [string, string, string]; e: string }
function expand(file: { skill: string; q: string; items: Compact[] }): Item[] {
  return file.items.map((x) => {
    assert.equal(x.c.length, 4, `need 4 choices: ${x.p.slice(0, 40)}`)
    assert.equal(x.w.length, 3, `need 3 rationales: ${x.p.slice(0, 40)}`)
    const at = [...x.p].reduce((h, ch) => (h * 31 + ch.charCodeAt(0)) >>> 0, 7) % 4
    const wrong = x.c.slice(1).map((text, i) => ({ text, why: x.w[i] }))
    const order = [...wrong.slice(0, at), { text: x.c[0], why: '' }, ...wrong.slice(at)]
    const ids = ['A', 'B', 'C', 'D']
    return {
      skill: file.skill, subskill: `${file.skill}.${x.s}`, tier: x.t, kind: 'mcq' as const, passage: x.p, stem: x.q ?? file.q,
      choices: order.map((o, i) => ({ id: ids[i], text: o.text })), answer: { choice: ids[at] },
      rationales: Object.fromEntries(order.flatMap((o, i) => (i === at ? [] : [[ids[i], o.why]]))), explanation: x.e,
    }
  })
}
const rwDir = new URL('data/items/rw/', root)
const rw: Item[] = [
  ...read('data/items/rw.json'),
  ...readdirSync(rwDir).filter((f) => f.endsWith('.json')).sort().flatMap((f) => expand(JSON.parse(readFileSync(new URL(f, rwDir), 'utf8')))),
]
const taxonomy = read('data/skill-taxonomy.json')

type Skill = { id: string; section: string; domain_id: string; domain_name: string; domain_share: number; name: string; sort: number }
const skills: Skill[] = []
const subskills = new Set<string>()
for (const s of taxonomy.sections)
  for (const d of s.domains)
    for (const k of d.skills) {
      skills.push({ id: k.id, section: s.id, domain_id: d.id, domain_name: d.name, domain_share: d.share, name: k.name, sort: skills.length })
      for (const x of k.subskills) subskills.add(x.id)
    }

// Validate every item before it reaches the database.
for (const it of [...rw, ...math]) {
  assert(skills.some((s) => s.id === it.skill), `unknown skill ${it.skill}`)
  assert(subskills.has(it.subskill) && it.subskill.startsWith(it.skill + '.'), `bad subskill ${it.subskill}`)
  assert(['easy', 'medium', 'hard'].includes(it.tier))
  assert(it.explanation.length > 20, `missing explanation: ${it.stem}`)
  if (it.kind === 'mcq') {
    const ids = it.choices!.map((c) => c.id)
    assert.deepEqual(ids, ['A', 'B', 'C', 'D'])
    const key = (it.answer as { choice: string }).choice
    assert(ids.includes(key))
    assert.equal(new Set(it.choices!.map((c) => c.text)).size, 4, `duplicate choices: ${it.stem}`)
    assert.deepEqual(Object.keys(it.rationales).sort(), ids.filter((i) => i !== key), `rationales must cover each wrong choice: ${it.stem}`)
  } else {
    assert('values' in it.answer && it.answer.values.length > 0)
  }
  if (it.passage && it.skill.startsWith('rw.')) {
    const words = it.passage.replace(/^Text \d$/gm, '').split(/\s+/).filter(Boolean).length
    assert(words >= 25 && words <= 150, `passage has ${words} words (SAT range is 25–150): ${it.passage.slice(0, 40)}`)
  }
}

const q = (v: unknown) => (v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`)
const j = (v: unknown) => (v == null ? 'null' : `${q(JSON.stringify(v))}::jsonb`)
const b = { easy: -1, medium: 0, hard: 1 }

const sql = [
  '-- Generated by scripts/build-seed.ts. Do not edit by hand.',
  'begin;',
  'insert into public.skills (id, section, domain_id, domain_name, domain_share, name, sort) values',
  skills.map((s) => `  (${[s.id, s.section, s.domain_id, s.domain_name].map(q).join(', ')}, ${s.domain_share}, ${q(s.name)}, ${s.sort})`).join(',\n'),
  'on conflict (id) do update set name = excluded.name, sort = excluded.sort, domain_share = excluded.domain_share;',
  'insert into public.items (skill_id, subskill_id, tier, b, kind, passage, stem, choices, answer, explanation, rationales) values',
  [...rw, ...math].map((it) =>
    `  (${q(it.skill)}, ${q(it.subskill)}, ${q(it.tier)}, ${b[it.tier]}, ${q(it.kind)}, ${q(it.passage)}, ${q(it.stem)}, ${j(it.choices)}, ${j(it.answer)}, ${q(it.explanation)}, ${j(it.rationales)})`,
  ).join(',\n') + ';',
  'commit;',
  '',
].join('\n')
writeFileSync(new URL('supabase/seed.sql', root), sql)
// Same items as JSON, for scripts/load-items.ts (loading a hosted project through the admin RPC).
writeFileSync(new URL('supabase/seed-items.json', root), JSON.stringify([...rw, ...math]))

const count = (xs: Item[]) => Object.entries(Object.groupBy(xs, (i) => `${i.skill}/${i.tier}`)).map(([k, v]) => `${k}:${v!.length}`).join(' ')
console.log(`skills ${skills.length}, items rw ${rw.length} + math ${math.length}`)
console.log(count([...rw, ...math]))
